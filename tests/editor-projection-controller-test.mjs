import assert from 'node:assert/strict';
import { ProjectionCoordinator } from '../src/renderer/core/projection-coordinator.js';
import { EditorProjectionController } from '../src/renderer/core/editor-projection-controller.mjs';
const deferred = () => { let resolve, reject; const promise = new Promise((yes, no) => { resolve = yes; reject = no; }); return { promise, resolve, reject }; };
let doc = { id: 'A', sourceRevision: 0, content: 'original' }, mode = false;
const coordinator = new ProjectionCoordinator(() => doc?.id, () => JSON.stringify([doc?.sourceRevision || 0, mode]));
let response, frames = [], activations = 0, captures = 0, errors = 0;
const source = { value: '' }, visual = { innerHTML: '', childNodes: [] }, pane = { scrollTo() {} };
const controller = new EditorProjectionController({ coordinator, source, visual, pane,
  render: () => response.promise, normalize() {}, capture() { captures++; }, activate() { activations++; },
  onError() { errors++; }, nextFrame: callback => frames.push(callback) });
response = deferred();
let pending = controller.project(doc, mode);
doc.sourceRevision++; doc.content = 'new source'; response.resolve({ html: 'stale' });
assert.equal(await pending, false); assert.equal(visual.innerHTML, ''); assert.equal(coordinator.loading, false);
response = deferred(); pending = controller.project(doc, mode);
mode = true; assert.equal(await controller.project(doc, mode), true);
response.reject(new Error('late failure'));
assert.equal(await pending, false); assert.equal(errors, 0); assert.equal(source.value, 'new source');
mode = false; response = deferred(); pending = controller.project(doc, mode);
response.resolve({ html: 'projection', spans: [] }); await Promise.resolve();
assert.equal(coordinator.loading, true, 'Activation frame must remain within loading');
assert.equal(frames.length, 1);
frames.shift()(); assert.equal(await pending, true);
assert.equal(coordinator.loading, false); assert.equal(captures, 1); assert.equal(activations, 2);
response = deferred(); const stale = controller.project(doc, mode);
response.resolve({ html: 'old frame' }); await Promise.resolve();
response = deferred(); const current = controller.project(doc, mode);
frames.shift()(); assert.equal(await stale, false);
assert.equal(coordinator.loading, true, 'Old activation cannot release new loading');
response.resolve({ html: 'new frame' }); await Promise.resolve(); frames.shift()();
assert.equal(await current, true); assert.equal(visual.innerHTML, 'new frame');
response = deferred(); pending = controller.project(doc, mode); response.reject(new Error('render failed'));
assert.equal(await pending, false); assert.equal(errors, 1); assert.equal(coordinator.loading, false);
doc = { id: 'empty', sourceRevision: 0, content: '' };
const empty = controller.project(doc, false);
assert.equal(visual.innerHTML, '<p><br></p>', 'Empty projection must be installed synchronously');
assert.equal(await empty, true);
assert.equal(await controller.project(null, false), false, 'No-document request must match active document');
doc = null; assert.equal(await controller.project(null, false), true);
console.log(JSON.stringify({ sourceRevisionGuard: true, staleModeFailure: true, frameOwnership: true, immediateEmpty: true, errorRecovery: true }));
